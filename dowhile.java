class dowhile{
    public static void main(String args[]){
        //do while loop is used to execute a block of statements repeatedly until a given condition is true. If the condition is false, the loop will terminate.
        //The do while loop is similar to the while loop, except that the do while loop will always execute the block of statements at least once, even if the condition is false.

        int i = 21;
        do{
            System.out.println(i);
            i++;
        }while(i<=20);//condition of do while loop
    }
}